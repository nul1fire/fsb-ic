function findCardAtPointer() {
  const cards = document.querySelectorAll(".card");
  for (const c of cards) {
    const r = c.getBoundingClientRect();
    if (mouseX >= r.left && mouseX <= r.right && mouseY >= r.top && mouseY <= r.bottom) return c;
  }
  return null;
}
